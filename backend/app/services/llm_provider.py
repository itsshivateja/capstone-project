import os
import json
import re
import httpx
from typing import List, Dict, Any, Optional
from app.config import settings

class LLMProvider:
    def __init__(self):
        self._refresh_keys()

    def _refresh_keys(self):
        self.gemini_key = settings.GEMINI_API_KEY or os.getenv("GEMINI_API_KEY", "")
        self.openai_key = settings.OPENAI_API_KEY or os.getenv("OPENAI_API_KEY", "")
        self.groq_key = settings.GROQ_API_KEY or os.getenv("GROQ_API_KEY", "")
        self.openai_base = settings.OPENAI_API_BASE or os.getenv("OPENAI_API_BASE", "https://api.openai.com/v1")

    async def generate_completion(
        self,
        system_prompt: str,
        user_prompt: str,
        temperature: float = 0.2,
        custom_key: Optional[str] = None
    ) -> str:
        """
        Query configured LLM provider or fallback to intelligent repository reasoning engine.
        """
        self._refresh_keys()

        # Try Groq API if key is present (High-Speed LPU: GPT-OSS-120B / Qwen-27B / LLaMA)
        groq = custom_key if (custom_key and custom_key.startswith("gsk_")) else self.groq_key
        if groq:
            for model_candidate in ["openai/gpt-oss-120b", "qwen/qwen3.8-27b", "openai/gpt-oss-20b", "llama-3.3-70b-versatile", "llama-3.1-8b-instant"]:
                try:
                    return await self._call_openai_compatible(
                        api_key=groq,
                        base_url="https://api.groq.com/openai/v1",
                        model=model_candidate,
                        system_prompt=system_prompt,
                        user_prompt=user_prompt,
                        temperature=temperature
                    )
                except Exception as e:
                    print(f"[LLM] Groq call with {model_candidate} failed: {e}")

        # Try Gemini API if key is present
        gemini = custom_key if (custom_key and custom_key.startswith("AIzaSy")) else self.gemini_key
        if gemini:
            try:
                return await self._call_gemini(gemini, system_prompt, user_prompt, temperature)
            except Exception as e:
                print(f"[LLM] Gemini call failed ({e}). Proceeding to fallback engine.")

        # Try OpenAI API if key is present
        openai = custom_key if (custom_key and custom_key.startswith("sk-")) else self.openai_key
        if openai:
            try:
                return await self._call_openai_compatible(
                    api_key=openai,
                    base_url=self.openai_base,
                    model=settings.DEFAULT_MODEL,
                    system_prompt=system_prompt,
                    user_prompt=user_prompt,
                    temperature=temperature
                )
            except Exception as e:
                print(f"[LLM] OpenAI call failed ({e}). Proceeding to fallback engine.")

        # High-Fidelity Domain Synthesis Engine (Autonomous Zero-Key Mode)
        return self._generate_intelligent_fallback(system_prompt, user_prompt)

    async def _call_gemini(self, api_key: str, system_prompt: str, user_prompt: str, temperature: float) -> str:
        url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key={api_key}"
        payload = {
            "contents": [
                {
                    "role": "user",
                    "parts": [{"text": f"SYSTEM INSTRUCTIONS:\n{system_prompt}\n\nUSER REQUEST:\n{user_prompt}"}]
                }
            ],
            "generationConfig": {
                "temperature": temperature,
                "maxOutputTokens": 2048,
            }
        }
        async with httpx.AsyncClient(timeout=30.0) as client:
            resp = await client.post(url, json=payload)
            resp.raise_for_status()
            data = resp.json()
            candidates = data.get("candidates", [])
            if candidates:
                return candidates[0]["content"]["parts"][0]["text"]
            return "No response generated by Gemini."

    async def _call_openai_compatible(self, api_key: str, base_url: str, model: str, system_prompt: str, user_prompt: str, temperature: float) -> str:
        url = f"{base_url.rstrip('/')}/chat/completions"
        headers = {
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json"
        }
        payload = {
            "model": model,
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt}
            ],
            "temperature": temperature,
            "max_tokens": 2048
        }
        async with httpx.AsyncClient(timeout=30.0) as client:
            resp = await client.post(url, headers=headers, json=payload)
            resp.raise_for_status()
            data = resp.json()
            choice = data["choices"][0]
            msg = choice.get("message", {})
            return msg.get("content") or msg.get("reasoning") or "No response received."

